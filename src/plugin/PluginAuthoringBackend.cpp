std::string PluginAuthoringBackend::slugify(const std::string& name) {
    std::string out;
    out.reserve(name.size());
    bool prevDash = false;
    for (char c : name) {
        if (std::isalnum(static_cast<unsigned char>(c))) {
            out += static_cast<char>(std::tolower(c));
            prevDash = false;
        } else if (c == '.' || c == '-') {
            if (!prevDash) { out += c; prevDash = true; }
        } else if (std::isspace(static_cast<unsigned char>(c)) || c == '_') {
            if (!prevDash && !out.empty()) { out += '-'; prevDash = true; }
        }
    }
    while (!out.empty() && (out.back() == '-' || out.back() == '.')) out.pop_back();
    return out;
}

bool PluginAuthoringBackend::isValidId(const std::string& id) {
    // Must match the JSON-schema pattern used by PluginValidator
    // (`^[a-z0-9-]+\.[a-z0-9-]+$`) — exactly one dot separating two
    // kebab-case segments.
    static const std::regex re("^[a-z0-9-]+\\.[a-z0-9-]+$");
    return std::regex_match(id, re);
}

std::vector<std::string> PluginAuthoringBackend::detectPermissions(
    const std::string& luaSource)
{
    static const std::pair<const char*, const char*> kMap[] = {
        {"bbfx.midi",         "midi"},
        {"bbfx.osc",          "osc"},
        {"bbfx.artnet",       "artnet"},
        {"bbfx.textureShare", "texture-share"},
        {"bbfx.gamepad",      "gamepad"},
        {"bbfx.joystick",     "gamepad"},
        {"bbfx.http",         "network"},
        {"bbfx.websocket",    "network"},
        {"bbfx.fs",           "fs"},
        {"bbfx.ui",           "ui"},
        {"bbfx.scene",        "scene"},
        {"bbfx.models",       "models"},
        {"bbfx.audio",        "audio"},
    };
    std::vector<std::string> out;
    for (auto& kv : kMap) {
        if (luaSource.find(kv.first) != std::string::npos) {
            // Avoid duplicates (e.g. gamepad + joystick both map to "gamepad").
            if (std::find(out.begin(), out.end(), kv.second) == out.end()) {
                out.emplace_back(kv.second);
            }
        }
    }
    return out;
}

