fs::path PluginAuthoringBackend::writePlugin(
    const fs::path& destRoot,
    const Metadata& meta,
    const std::string& initLuaBody,
    const std::vector<std::pair<std::string, std::string>>& extraFiles)
{
    if (meta.id.empty()) {
        std::cerr << "[PluginAuthoringBackend] writePlugin: empty id" << std::endl;
        return {};
    }
    if (!isValidId(meta.id)) {
        std::cerr << "[PluginAuthoringBackend] writePlugin: invalid id '"
                   << meta.id << "'" << std::endl;
        return {};
    }
    std::error_code ec;
    fs::path pluginDir = destRoot / meta.id;
    fs::create_directories(pluginDir, ec);
    if (ec) {
        std::cerr << "[PluginAuthoringBackend] cannot create " << pluginDir
                   << ": " << ec.message() << std::endl;
        return {};
    }
    try {
        // manifest.json
        writeText(pluginDir / "manifest.json",
                    buildManifest(meta).dump(2) + "\n");
        // init.lua
        writeText(pluginDir / "init.lua",
                    initLuaBody.empty() ? std::string("return {}\n") : initLuaBody);
        // README.md (template)
        std::string readme = "# " + meta.name + "\n\n" + meta.description + "\n\n"
            + "**Author:** " + meta.author + "\n\n"
            + "**License:** " + meta.license + "\n\n"
            + "Generated by BBFx Studio Plugin Authoring.\n";
        writeText(pluginDir / "README.md", readme);
        // Copy resources
        for (auto& [rel, src] : extraFiles) {
            if (rel.empty() || src.empty()) continue;
            fs::path dst = pluginDir / rel;
            fs::create_directories(dst.parent_path(), ec);
            fs::copy_file(src, dst,
                           fs::copy_options::overwrite_existing, ec);
            if (ec) {
                std::cerr << "[PluginAuthoringBackend] copy " << src << " -> "
                           << dst << " failed: " << ec.message() << std::endl;
            }
        }
    } catch (const std::exception& e) {
        std::cerr << "[PluginAuthoringBackend] writePlugin failed: "
                   << e.what() << std::endl;
        // Rollback: best-effort remove the partially-created directory.
        fs::remove_all(pluginDir, ec);
        return {};
    }
    return pluginDir;
}

fs::path PluginAuthoringBackend::exportScenePreset(
    const Metadata& inMeta, const nlohmann::json& sceneJson)
{
    Metadata meta = inMeta;
    if (meta.category != "Scene") meta.category = "Scene";
    // Auto-set permission `scene` since the init.lua restores scene state.
    if (std::find(meta.permissions.begin(), meta.permissions.end(),
                   std::string("scene")) == meta.permissions.end()) {
        meta.permissions.emplace_back("scene");
    }
    std::string init =
        "-- v3.5 Lot S — Scene preset plugin.\n"
        "-- Restores a captured scene state when enabled.\n"
        "local scene = " + sceneJson.dump() + "\n"
        "return {\n"
        "    onEnable = function()\n"
        "        if bbfx.scene and bbfx.scene.applyPreset then\n"
        "            bbfx.scene.applyPreset(scene)\n"
        "        else\n"
        "            print('[" + meta.id + "] bbfx.scene.applyPreset not available')\n"
        "        end\n"
        "    end,\n"
        "    capture = scene,\n"
        "}\n";
    return writePlugin(PluginManager::instance().getUserPluginsDir(),
                        meta, init, {});
}

fs::path PluginAuthoringBackend::exportOutputTemplate(
    const Metadata& inMeta, const nlohmann::json& outputJson)
{
    Metadata meta = inMeta;
    if (meta.category != "OutputTemplate") meta.category = "OutputTemplate";
    // Output manager config restoration needs `scene` perm (applies
    // cameras + render target changes).
    if (std::find(meta.permissions.begin(), meta.permissions.end(),
                   std::string("scene")) == meta.permissions.end()) {
        meta.permissions.emplace_back("scene");
    }
    std::string init =
        "-- v3.5 Lot S — Output template plugin.\n"
        "local outputs = " + outputJson.dump() + "\n"
        "return {\n"
        "    onEnable = function()\n"
        "        if bbfx.output and bbfx.output.applyTemplate then\n"
        "            bbfx.output.applyTemplate(outputs)\n"
        "        else\n"
        "            print('[" + meta.id + "] bbfx.output.applyTemplate not available')\n"
        "        end\n"
        "    end,\n"
        "    capture = outputs,\n"
        "}\n";
    return writePlugin(PluginManager::instance().getUserPluginsDir(),
                        meta, init, {});
}

fs::path PluginAuthoringBackend::exportSubgraph(
    const Metadata& inMeta, const nlohmann::json& subgraphJson)
{
    Metadata meta = inMeta;
    if (meta.category.empty()) meta.category = "Node";
    std::string init =
        "-- v3.5 Lot S — Node subgraph plugin.\n"
        "-- Re-instantiates a captured subgraph on each enable.\n"
        "local spec = " + subgraphJson.dump() + "\n"
        "return {\n"
        "    onEnable = function()\n"
        "        for _, n in ipairs(spec.nodes or {}) do\n"
        "            if bbfx.createNode then bbfx.createNode(n.type, n.name) end\n"
        "        end\n"
        "        for _, l in ipairs(spec.links or {}) do\n"
        "            if bbfx.link then bbfx.link(l.src, l.srcPort, l.dst, l.dstPort) end\n"
        "        end\n"
        "    end,\n"
        "    spec = spec,\n"
        "}\n";
    return writePlugin(PluginManager::instance().getUserPluginsDir(),
                        meta, init, {});
}

