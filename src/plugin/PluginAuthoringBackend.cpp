nlohmann::json buildManifest(const PluginAuthoringBackend::Metadata& meta) {
    using nlohmann::json;
    json j;
    j["id"]           = meta.id;
    j["name"]         = meta.name.empty() ? meta.id : meta.name;
    j["version"]      = meta.version;
    j["type"]         = (meta.category == "Scene" || meta.category == "OutputTemplate")
                          ? meta.category
                          : std::string("Node");
    j["bbfx_version"] = meta.bbfxVersion;
    j["description"]  = meta.description;
    j["category"]     = meta.category;
    j["license"]      = meta.license;
    j["entry"]        = "init.lua";
    json author;
    author["name"] = meta.author.empty() ? std::string("BBFx Studio user") : meta.author;
    j["author"]    = author;
    if (!meta.tags.empty())        j["tags"]        = meta.tags;
    if (!meta.permissions.empty()) j["permissions"] = meta.permissions;
    return j;
}

void writeText(const fs::path& p, const std::string& body) {
    std::ofstream f(p, std::ios::binary);
    f.write(body.data(), static_cast<std::streamsize>(body.size()));
}

